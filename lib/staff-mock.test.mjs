test('report messaging creates separate reporter and reported-user conversations, with purpose-bound audits', async () => {
  const m = mk('mod');
  const reportId = m.t.sx_reports[0].id;
  const open = (audience, reason = 'Onderzoek deze melding') => m.rpc('sx_staff_report_conversation', { p_report_id: reportId, p_audience: audience, p_reason: reason });
  const first = await open('reporter');
  assert.equal(first.error, null);
  assert.equal(first.data[0].recipient_id, I.aria);
  assert.equal(first.data[0].thread_id, null);
  const reporterSend = await m.rpc('sx_staff_send_report_message', { p_report_id: reportId, p_audience: 'reporter', p_body: 'We onderzoeken je melding.', p_reason: 'Contact met de melder' });
  const reportedSend = await m.rpc('sx_staff_send_report_message', { p_report_id: reportId, p_audience: 'reported', p_body: 'We willen je spreken over een melding.', p_reason: 'Contact met de gebruiker' });
  assert.equal(reporterSend.error, null);
  assert.equal(reportedSend.error, null);
  assert.notEqual(reporterSend.data.thread_id, reportedSend.data.thread_id);
  assert.equal(reporterSend.data.recipient_id, I.aria);
  assert.equal(reportedSend.data.recipient_id, I.bram);
  assert.equal(m.t.sx_report_conversations.length, 2);
  const reporterThread = m.t.sx_threads.find(t => t.id === reporterSend.data.thread_id);
  const reportedThread = m.t.sx_threads.find(t => t.id === reportedSend.data.thread_id);
  assert.equal(reporterThread.member_count, 2);
  assert.equal(reportedThread.member_count, 2);
  const reporterRead = await open('reporter');
  const reportedRead = await open('reported');
  assert.deepEqual(reporterRead.data.map(x => x.body), ['We onderzoeken je melding.']);
  assert.deepEqual(reportedRead.data.map(x => x.body), ['We willen je spreken over een melding.']);
  const sendAudit = m.t.audit_logs.filter(a => a.action === 'sx_staff_report_message_sent');
  assert.equal(sendAudit.length, 2);
  assert.ok(sendAudit.every(a => a.metadata.reason && a.metadata.report_id === reportId));
  assert.ok(sendAudit.every(a => !JSON.stringify(a.metadata).includes('We onderzoeken je melding.')));
  assert.equal((await open('reporter', 'te kort')).error.message.includes('at least 10'), true);
  m.actorId = I.aria;
  assert.equal((await m.rpc('sx_staff_send_report_message', { p_report_id: reportId, p_audience: 'reporter', p_body: 'Niet toegestaan', p_reason: 'Voldoende reden' })).error.code, '42501');
});

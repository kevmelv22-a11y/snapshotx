// Regenerates components/avatar/bodyLayerRegistry.ts from assets/avatar-art/body/{male,female}/*.png.
// Run after adding layer images: node scripts/gen-body-layers.mjs
import { readdirSync, existsSync, writeFileSync } from 'node:fs';
const root = 'assets/avatar-art/body';
const lines = [];
for (const g of ['male', 'female']) {
  const dir = `${root}/${g}`;
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir).filter(f => f.endsWith('.png')).sort())
    lines.push(`  '${g}/${f.slice(0, -4)}': require('../../${dir}/${f}'),`);
}
writeFileSync('components/avatar/bodyLayerRegistry.ts', `/* Generated by scripts/gen-body-layers.mjs — do not edit. */
/* eslint-disable @typescript-eslint/no-require-imports */
export const BODY_LAYERS: Record<string, number> = {
${lines.join('\n')}
};
`);
console.log(`${lines.length} layers`);

// Generates lib/avatar/wornStyleInfo.ts (pure rects) + lib/wornStyles.ts (require map) from scripts/worn-bands/styles.json
// (written by scripts/worn-bands/hairstyles.py). Run: node scripts/gen-worn-styles.mjs
// Only keep bands of items the app draws (lib/avatar/wornBandInfo) are referenced.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const styles = JSON.parse(readFileSync(new URL('./worn-bands/styles.json', import.meta.url), 'utf8'));
const bandsSrc = readFileSync(new URL('../lib/avatar/wornBandInfo.ts', import.meta.url), 'utf8');
const bands = JSON.parse(bandsSrc.slice(bandsSrc.indexOf('BandSet> = ') + 11, bandsSrc.lastIndexOf('}') + 1));
const info = { male: { styles: {}, keep: {}, clean: {} }, female: { styles: {}, keep: {}, clean: {} } }, req = [];
// female: hair-free torso / under / jacket bands (scripts/worn-bands/female/clean.py + tones-clean.sh), drawn instead of
// the art's bands (whose long hair would show under a Kapsel); same rect as the original band.
const clean = JSON.parse(readFileSync(new URL('./worn-bands/female/clean.json', import.meta.url), 'utf8'));
const cleanTones = JSON.parse(readFileSync(new URL('./worn-bands/female/clean-tones.json', import.meta.url), 'utf8'));
const add = (key, f) => {
  if (!existsSync(new URL(`../${f}`, import.meta.url))) throw new Error(f);
  req.push(`  '${key}': require('../${f}'),`);
};
for (const g of ['female', 'male']) {
  const s = styles[g]; if (!s) continue;
  for (const [id, { rect, tones }] of Object.entries(s.styles)) {
    info[g].styles[id] = { rect, tones };
    add(`${g}/style/${id}`, `assets/avatar-art/worn-styles/${g}/style-${id}.png`);
    for (const k of Object.keys(tones)) add(`${g}/style/${id}/${k}`, `assets/avatar-art/worn-styles/${g}/style-${id}--${k}.png`);
  }
  for (const [item, { rect, tones }] of Object.entries(s.keep)) {
    if (!bands[g].items[item]?.bands.head || !rect) continue;
    info[g].keep[item] = { rect, tones };
    add(`${g}/keep/${item}`, `assets/avatar-art/worn-styles/${g}/${item}-keep.png`);
    for (const k of Object.keys(tones)) add(`${g}/keep/${item}/${k}`, `assets/avatar-art/worn-styles/${g}/${item}-keep--${k}.png`);
  }
}
for (const [item, bandList] of Object.entries(clean)) {
  if (!bands.female.items[item]) continue;
  for (const b of bandList) {
    if (!bands.female.items[item].bands[b]) continue;
    const tones = cleanTones[`${item}-${b}`] ?? {};
    info.female.clean[`${item}/${b}`] = tones;
    add(`female/clean/${item}/${b}`, `assets/avatar-art/worn-clean/female/${item}-${b}.png`);
    for (const k of Object.keys(tones)) add(`female/clean/${item}/${b}/${k}`, `assets/avatar-art/worn-clean/female/${item}-${b}--${k}.png`);
  }
}
writeFileSync(new URL('../lib/avatar/wornStyleInfo.ts', import.meta.url), `// GENERATED by scripts/gen-worn-styles.mjs: do not edit.
// Hairstyle layers (canvas rect) with their 's-<tone>' / 'h-<colour>' overlays (rect inside the layer), and per item the
// head band without its old face + hair ('keep', rect inside the head band) with its skin overlays (keep tone rects: inside the head band too).
// clean: '<item>/<band>' hair-free torso / under / jacket bands (female; same rect as the band) -> their skin overlays (rect inside the band).
type Rect = [number, number, number, number];
export type StyleLayer = { rect: Rect; tones: Record<string, Rect> };
export const WORN_STYLES: Record<'male' | 'female', { styles: Record<string, StyleLayer>; keep: Record<string, StyleLayer>; clean: Record<string, Record<string, Rect>> }> = ${JSON.stringify(info)};
`);
writeFileSync(new URL('../lib/wornStyles.ts', import.meta.url), `// GENERATED by scripts/gen-worn-styles.mjs: do not edit. Key = '<gender>/style/<id>[/<tone>]', '<gender>/keep/<itemId>[/<tone>]' or 'female/clean/<itemId>/<band>[/<tone>]'.
/* eslint-disable @typescript-eslint/no-require-imports */
export const WORN_STYLE_SRC: Record<string, number> = {
${req.join('\n')}
};
`);
console.log(req.length, 'style images');

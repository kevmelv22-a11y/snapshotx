// Generates lib/avatar/wornToneInfo.ts (pure overlay rects) + lib/wornTones.ts (require map) from
// scripts/worn-bands/tones.json (written by scripts/worn-bands/tones.py). Run: node scripts/gen-worn-tones.mjs
// Only overlays of bands the app actually draws (lib/avatar/wornBandInfo) are referenced.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const tones = JSON.parse(readFileSync(new URL('./worn-bands/tones.json', import.meta.url), 'utf8'));
const bandsSrc = readFileSync(new URL('../lib/avatar/wornBandInfo.ts', import.meta.url), 'utf8');
const bands = JSON.parse(bandsSrc.slice(bandsSrc.indexOf('BandSet> = ') + 11, bandsSrc.lastIndexOf('}') + 1));
const info = {}, req = [];
for (const g of ['female', 'male']) {
  info[g] = {};
  for (const [name, overlays] of tones[g].files) {
    const i = name.lastIndexOf('-'), item = name.slice(0, i), band = name.slice(i + 1);
    if (!bands[g].items[item]?.bands[band]) continue;
    const rects = {};
    for (const [key, rect] of overlays) {
      const f = `assets/avatar-art/worn-tones/${g}/${name}--${key}.png`;
      if (!existsSync(new URL(`../${f}`, import.meta.url))) throw new Error(f);
      rects[key] = rect; req.push(`  '${g}/${item}/${band}/${key}': require('../${f}'),`);
    }
    info[g][`${item}/${band}`] = rects;
  }
}
writeFileSync(new URL('../lib/avatar/wornToneInfo.ts', import.meta.url), `// GENERATED by scripts/gen-worn-tones.mjs: do not edit.
// Skin-tone ('s-<tone>') and hair-colour ('h-<colour>') overlays per band: rect [x, y, w, h] inside the band image.
export type ToneRects = Record<string, [number, number, number, number]>;
export const ORIGINAL_HAIR = ${JSON.stringify({ male: tones.male.origHair, female: tones.female.origHair })} as const;
export const WORN_TONES: Record<'male' | 'female', Record<string, ToneRects>> = ${JSON.stringify(info)};
`);
writeFileSync(new URL('../lib/wornTones.ts', import.meta.url), `// GENERATED by scripts/gen-worn-tones.mjs: do not edit. Key = '<gender>/<itemId>/<band>/<s-tone|h-colour>'.
/* eslint-disable @typescript-eslint/no-require-imports */
export const WORN_TONE_SRC: Record<string, number> = {
${req.join('\n')}
};
`);
console.log(req.length, 'tone overlays');

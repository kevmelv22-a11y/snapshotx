// Generates lib/wornArt.ts from assets/avatar-art/worn/<gender>/<itemId>.png (run: node scripts/gen-worn-art.mjs).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../assets/avatar-art/worn/', import.meta.url);
const size = f => { const b = readFileSync(f); return [b.readUInt32BE(16), b.readUInt32BE(20)]; };
const lines = [];
for (const g of ['female', 'male']) for (const f of readdirSync(new URL(g + '/', root)).filter(f => f.endsWith('.png')).sort()) {
  const [w, h] = size(new URL(`${g}/${f}`, root));
  lines.push(`  '${g}/${f.slice(0, -4)}': { src: require('../assets/avatar-art/worn/${g}/${f}'), w: ${w}, h: ${h} },`);
}
writeFileSync(new URL('../lib/wornArt.ts', import.meta.url), `// GENERATED by scripts/gen-worn-art.mjs: do not edit. Key = '<gender>/<itemId>'.
/* eslint-disable @typescript-eslint/no-require-imports */
export const WORN_ART: Record<string, { src: number; w: number; h: number }> = {
${lines.join('\n')}
};
`);
console.log(lines.length, 'worn images');

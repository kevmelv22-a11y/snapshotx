// Generates lib/avatar/wornBandInfo.ts (pure rects/flags) + lib/wornBands.ts (require map) from
// scripts/worn-bands/meta.json (written by scripts/worn-bands/build.py). Run: node scripts/gen-worn-bands.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const meta = JSON.parse(readFileSync(new URL('./worn-bands/meta.json', import.meta.url), 'utf8'));
const FIG = { male: [60, 700], female: [60, 703] }; // figure top (canvas px) + reference figure height (build.py PT / ref height)
const info = {}, req = [];
for (const g of ['female', 'male']) {
  const [w, h] = meta[g].canvas; info[g] = { canvas: { w, h, figTop: FIG[g][0], figH: FIG[g][1] }, items: {} };
  for (const id of Object.keys(meta[g].pieces).sort()) {
    const p = meta[g].pieces[id]; const bands = {};
    for (const b of ['head', 'torso', 'jacket', 'legs', 'sole', 'feet']) if (p[b] && (b !== 'jacket' || meta._open?.[`${g}/${id}`] > 0)) { // jacket cutout only for open jackets
      const f = `assets/avatar-art/worn-bands/${g}/${id}-${b}.png`;
      if (!existsSync(new URL(`../${f}`, import.meta.url))) throw new Error(f);
      bands[b] = p[b]; req.push(`  '${g}/${id}/${b}': require('../${f}'),`);
    }
    info[g].items[id] = { cat: p.cat, long: p.long, bands };
  }
}
writeFileSync(new URL('../lib/avatar/wornBandInfo.ts', import.meta.url), `// GENERATED by scripts/gen-worn-bands.mjs: do not edit.
// Registered band crops of the worn art: rects [x, y, w, h] on a shared per-gender canvas.
export type Band = 'head' | 'torso' | 'jacket' | 'legs' | 'sole' | 'feet';
export type BandItem = { cat: string; long: boolean; bands: Partial<Record<Band, [number, number, number, number]>> };
export type BandSet = { canvas: { w: number; h: number; figTop: number; figH: number }; items: Record<string, BandItem> };
export const WORN_BANDS: Record<'male' | 'female', BandSet> = ${JSON.stringify(info)};
`);
writeFileSync(new URL('../lib/wornBands.ts', import.meta.url), `// GENERATED by scripts/gen-worn-bands.mjs: do not edit. Key = '<gender>/<itemId>/<band>'.
/* eslint-disable @typescript-eslint/no-require-imports */
export const WORN_BAND_SRC: Record<string, number> = {
${req.join('\n')}
};
`);
console.log(req.length, 'band images');
